"""Draw the 20 eval origin and destination pairs and write ``eval/od_pairs.yaml``.

Pairs come from walk-graph nodes inside the Boston boundary, sampled with
``random.Random(2026)``, with straight-line distance from 1.5 km to 8 km, each on
Tuesday at 08:15. ``transit/cache_trips.py`` and ``eval/run.py`` read the output.
"""

from __future__ import annotations

import json
import math
import random
from pathlib import Path

import networkx as nx
import yaml
from shapely import prepared
from shapely.geometry import Point as ShapelyPoint
from shapely.geometry import shape
from shapely.ops import unary_union

from commute_agent.paths import EVAL, PROCESSED

SEED = 2026
N_PAIRS = 20
MIN_M = 1500.0
MAX_M = 8000.0
WEEKDAY = "tuesday"
DEPART_LOCAL = "08:15"
COORD_DECIMALS = 6
OUT = EVAL / "od_pairs.yaml"

HEADER = """\
# Eval origin and destination pairs. Generated by `uv run python eval/sample_pairs.py`;
# do not edit by hand. Shape: a list of rows, each
#   name: str               "od-NN"
#   origin: {lat, lon}      WGS84 degrees, a walk-graph node inside the Boston boundary
#   destination: {lat, lon} same
#   weekday: str            lowercase weekday name
#   depart_local: str       "HH:MM" in America/New_York
# Sampled with random.Random(2026); straight-line distance 1.5 km to 8 km.
"""


def haversine_m(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6_371_000.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def load_boundary(path: Path = PROCESSED / "boston_boundary.geojson"):
    geojson = json.loads(path.read_text())
    return unary_union([shape(f["geometry"]) for f in geojson["features"]])


def candidate_nodes(
    walk_graphml: Path = PROCESSED / "walk.graphml",
    boundary_path: Path = PROCESSED / "boston_boundary.geojson",
) -> list[tuple[float, float]]:
    """(lat, lon) of every walk-graph node inside the boundary, in node-id order."""
    graph = nx.read_graphml(walk_graphml)
    inside = prepared.prep(load_boundary(boundary_path))
    points: list[tuple[float, float]] = []
    for node_id in sorted(graph.nodes, key=int):
        data = graph.nodes[node_id]
        lat = round(float(data["y"]), COORD_DECIMALS)
        lon = round(float(data["x"]), COORD_DECIMALS)
        if inside.contains(ShapelyPoint(lon, lat)):
            points.append((lat, lon))
    return points


def sample_pairs(points: list[tuple[float, float]], rng: random.Random) -> list[dict]:
    rows: list[dict] = []
    while len(rows) < N_PAIRS:
        (olat, olon), (dlat, dlon) = rng.choice(points), rng.choice(points)
        if not MIN_M <= haversine_m(olat, olon, dlat, dlon) <= MAX_M:
            continue
        rows.append(
            {
                "name": f"od-{len(rows) + 1:02d}",
                "origin": {"lat": olat, "lon": olon},
                "destination": {"lat": dlat, "lon": dlon},
                "weekday": WEEKDAY,
                "depart_local": DEPART_LOCAL,
            }
        )
    return rows


def main() -> int:
    rows = sample_pairs(candidate_nodes(), random.Random(SEED))
    OUT.write_text(HEADER + yaml.safe_dump(rows, sort_keys=False))
    print(f"wrote {len(rows)} pairs to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
